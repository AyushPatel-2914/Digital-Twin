# ── terrain & pit logic ────────────────────────────────────────────────
def _pit_centers():
    groups = {"fw":[],"n":[],"ne":[],"s":[]}
    for name,(x,y) in _RAW.items():
        if "fw_pit" in name:   groups["fw"].append((x,y))
        elif "n_q"  in name:   groups["n"].append((x,y))
        elif "ne_q" in name:   groups["ne"].append((x,y))
        elif "s_sp" in name:   groups["s"].append((x,y))
    out=[]
    for g in groups.values():
        if g:
            out.append((np.mean([p[0] for p in g]),np.mean([p[1] for p in g])))
    return out

_PIT_CENTERS = _pit_centers()

def _get_z(x,y):
    base = 0.02*x + 0.015*y + 20*np.sin(x/200) + 15*np.cos(y/150)
    for cx,cy in _PIT_CENTERS:
        d = math.hypot(x-cx, y-cy)
        if d < 220:
            base -= (220-d)*1.3
    return base

# ── build NODES with Z ─────────────────────────────────────────────────
