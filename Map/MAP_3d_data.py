# ── clean EDGES (all must be 2-tuples) ────────────────────────────────
EDGES = [(a,b) for a,b in _EDGE_RAW if a in NODES and b in NODES]

# ── smooth elevation along roads ───────────────────────────────────────
def _smooth(nodes, edges, iters=7):
    for _ in range(iters):
        nxt = {}
        for node in nodes:
            nbrs = [v for u,v in edges if u==node and v in nodes] + \
                   [u for u,v in edges if v==node and u in nodes]
            x,y,z = nodes[node]
            if nbrs:
                avg = np.mean([nodes[n][2] for n in nbrs])
                nxt[node] = np.array([x, y, 0.7*z + 0.3*avg])
            else:
                nxt[node] = nodes[node]
        nodes.update(nxt)

_smooth(NODES, EDGES)

# ── build road graph (undirected, weighted by 3-D distance) ───────────
def _build_graph(nodes, edges):
    g = {n:[] for n in nodes}
    for a,b in edges:
        if a in nodes and b in nodes:
            d = float(np.linalg.norm(nodes[a]-nodes[b]))
            g[a].append((b,d))
            g[b].append((a,d))
    return g

ROAD_GRAPH = _build_graph(NODES, EDGES)

